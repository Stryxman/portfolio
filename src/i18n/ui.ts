// Variables entre accolades : fmt("fr", "period.since", { y: 2024 }) → « Depuis 2024 »
export const fmt = (locale: Locale, key: UiKey, vars: Record<string, string | number>): string =>
  t(locale, key).replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
